#!/usr/bin/env python3
"""Add N staggered forwarding relays to test_configs/selfish_micro_sop.yaml.

The 12-daemon SoP network measured 2026-10-19..21 has a single bridge, six
seeds and two relays. A scale run keeps those hosts and the three miners as
they are (same 10 h/s, same D0 = 1200 chain, same alpha) and adds N daemon-only
relays, so only the propagation graph changes.

Start schedule: the linear start of docs/PERFORMANCE_AND_SCALE.md (relays one
per 10 s from 20 min). Starting every relay at once is what ran the 32 GB box
out of RAM near 500 nodes; KSM only merges pages as fast as it scans, so the
stagger bounds the un-merged boot footprint (~320 MB per monerod before KSM).

Log volume: all but every KEEP_EVERY-th added relay run monerod at log-level 0
(the ladder's relay setting). The kept ones log at monitor level so the SoP
oracle and the lateness probe have relays to check at scale. The three miners,
the bridge, the seeds and the original relays are unchanged.

  venv/bin/python scripts/make_sop_scale_base.py --extra 1000 \\
      -o test_configs/selfish_micro_sop_scale1000.yaml
"""
import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BASE = REPO / "test_configs/selfish_micro_sop.yaml"
ANCHOR = "  simulation-monitor:\n"


def relay_lines(extra: int, first_start_s: int, interval_s: int, keep_every: int) -> list:
    """One flow-style line per added relay, named scale-0001.. in start order."""
    lines = []
    width = max(4, len(str(extra)))
    for i in range(extra):
        start = first_start_s + i * interval_s
        quiet = keep_every <= 0 or (i + 1) % keep_every != 0
        opts = ", daemon_options: {log-level: 0}" if quiet else ""
        lines.append(f"  scale-{i + 1:0{width}d}: {{daemon: monerod, start_time: {start}s{opts}}}\n")
    return lines


def build(base_text: str, extra: int, first_start_s: int = 1200, interval_s: int = 10,
          keep_every: int = 50, command: str = "") -> str:
    """base_text with `extra` relays inserted before the simulation monitor and
    a header saying how the file was made. Raises ValueError on a base that
    doesn't have exactly one `  simulation-monitor:` line to insert before."""
    if extra < 1:
        raise ValueError("extra must be at least 1")
    if interval_s < 1 or first_start_s < 0:
        raise ValueError("interval_s must be positive and first_start_s non-negative")
    if base_text.count(ANCHOR) != 1:
        raise ValueError(f"base must contain exactly one {ANCHOR.strip()!r} line")
    last = first_start_s + (extra - 1) * interval_s
    kept = sum(1 for i in range(extra) if keep_every > 0 and (i + 1) % keep_every == 0)
    header = (
        f"# GENERATED by scripts/make_sop_scale_base.py{(' (' + command + ')') if command else ''}; "
        f"edit the base, not this file.\n"
        f"# selfish_micro_sop.yaml plus {extra} relays (scale-*) starting one per {interval_s} s from "
        f"{first_start_s} s (last at {last} s = {last / 3600:.2f} h).\n"
        f"# {kept} of them log at monitor level, the rest at log-level 0. Hosts: 13 + {extra} = {13 + extra}.\n"
        f"# Everything else, including bootstrap_end_time and the miners, is the base's.\n"
    )
    head, tail = base_text.split(ANCHOR)
    return header + head + "".join(relay_lines(extra, first_start_s, interval_s, keep_every)) + ANCHOR + tail


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--extra", type=int, required=True, help="number of relays to add")
    ap.add_argument("--base", default=str(BASE))
    ap.add_argument("--first-start", type=int, default=1200, help="seconds (default 1200 = 20 min)")
    ap.add_argument("--interval", type=int, default=10, help="seconds between relay starts (default 10)")
    ap.add_argument("--keep-every", type=int, default=50,
                    help="every Nth added relay keeps monitor-level logs; 0 = none (default 50)")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    cmd = f"--extra {a.extra} --first-start {a.first_start} --interval {a.interval} --keep-every {a.keep_every}"
    try:
        text = build(Path(a.base).read_text(), a.extra, a.first_start, a.interval, a.keep_every, cmd)
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    Path(a.output).write_text(text)
    print(f"wrote {a.output}: {a.extra} relays added")
    return 0


if __name__ == "__main__":
    sys.exit(main())
